package netpolicy

import (
	"net/netip"
	"strconv"
	"strings"
)

// renderIPTables renders an idempotent shell ruleset for the host's iptables and
// ip6tables binaries. A single iptables-restore file cannot carry both address
// families nor an idempotent jump into FORWARD, therefore the generated artifact
// is an executable /bin/sh ruleset (documented deviation from the pure
// iptables-restore file; it can be inspected and applied with `sh`).
func renderIPTables(plan Plan) string {
	var builder strings.Builder
	builder.WriteString("#!/bin/sh\n")
	builder.WriteString("# generated by retailgate netpolicy --format iptables\n")
	builder.WriteString("# chain " + ChainName + " in FORWARD: new management connections to protected\n")
	builder.WriteString("# controllers are accepted only from the listed gate sources; everything else\n")
	builder.WriteString("# is logged and dropped. Re-applying this script is idempotent.\n")
	builder.WriteString("# Honest limit: only traffic that traverses this host is enforced (routing/NAT/bridge required).\n")
	builder.WriteString("# protected endpoints: " + endpointList(plan) + "\n")
	builder.WriteString("# gate sources: " + strings.Join(plan.sourceSummary(), ", ") + "\n")
	builder.WriteString("set -eu\n\n")

	hasV4 := len(plan.SourcesV4) > 0 && len(v4Endpoints(plan)) > 0
	hasV6 := len(plan.SourcesV6) > 0 && len(v6Endpoints(plan)) > 0
	if hasV4 {
		builder.WriteString(renderIPTablesFamily("iptables", v4Endpoints(plan), plan.SourcesV4))
	}
	if hasV6 {
		builder.WriteString(renderIPTablesFamily("ip6tables", v6Endpoints(plan), plan.SourcesV6))
	}
	builder.WriteString("# end of generated ruleset\n")
	return builder.String()
}

// renderIPTablesFamily renders one address family block. The chain is flushed and
// rebuilt on every run; the FORWARD jump is inserted only when missing.
func renderIPTablesFamily(binary string, endpoints []Endpoint, sources []netip.Prefix) string {
	var builder strings.Builder
	builder.WriteString("# --- " + binary + " ---\n")
	builder.WriteString(binary + " -w -N " + ChainName + " 2>/dev/null || true\n")
	builder.WriteString("while " + binary + " -w -C FORWARD -j " + ChainName + " 2>/dev/null; do " +
		binary + " -w -D FORWARD -j " + ChainName + "; done\n")
	builder.WriteString(binary + " -w -I FORWARD 1 -j " + ChainName + "\n")
	builder.WriteString(binary + " -w -F " + ChainName + "\n")
	builder.WriteString(binary + " -w -A " + ChainName + " -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT\n")
	for _, endpoint := range endpoints {
		comment := cleanupComment(endpointComment(endpoint))
		for _, source := range sources {
			builder.WriteString(binary + " -w -A " + ChainName + " -s " + source.String() + " -p tcp -d " +
				endpoint.IP.String() + " --dport " + strconv.Itoa(int(endpoint.Port)) +
				" -m comment --comment \"" + comment + "\" -j ACCEPT\n")
		}
		builder.WriteString(binary + " -w -A " + ChainName + " -p tcp -d " + endpoint.IP.String() + " --dport " +
			strconv.Itoa(int(endpoint.Port)) + " -m comment --comment \"retailgate: deny non-gate sources\" -j LOG --log-prefix \"" +
			strings.TrimSpace(LogPrefix) + " \"\n")
		builder.WriteString(binary + " -w -A " + ChainName + " -p tcp -d " + endpoint.IP.String() + " --dport " +
			strconv.Itoa(int(endpoint.Port)) + " -j DROP\n")
	}
	builder.WriteString("\n")
	return builder.String()
}

// rollbackIPTables removes the jump and the dedicated chain for both families.
func rollbackIPTables() string {
	var builder strings.Builder
	builder.WriteString("#!/bin/sh\n")
	builder.WriteString("# generated by retailgate netpolicy --format iptables (rollback)\n")
	builder.WriteString("# removes the " + ChainName + " chain and its FORWARD jump; idempotent.\n")
	builder.WriteString("set -eu\n")
	for _, binary := range []string{"iptables", "ip6tables"} {
		builder.WriteString(binary + " -w -N " + ChainName + " 2>/dev/null || true\n") // ensure format of -F/-X below works on missing chain
		builder.WriteString("while " + binary + " -w -C FORWARD -j " + ChainName + " 2>/dev/null; do " +
			binary + " -w -D FORWARD -j " + ChainName + "; done\n")
		builder.WriteString(binary + " -w -F " + ChainName + " 2>/dev/null || true\n")
		builder.WriteString(binary + " -w -X " + ChainName + " 2>/dev/null || true\n")
	}
	builder.WriteString("echo \"retailgate: iptables ruleset rolled back\"\n")
	return builder.String()
}

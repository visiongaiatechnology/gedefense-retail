package netpolicy

import (
	"net/netip"
	"strconv"
	"strings"
)

// renderNFTables renders the dedicated inet table. It never touches default
// policies or chains of the host: the table only hooks the forward path at
// priority -5 (before the default filter policy).
func renderNFTables(plan Plan) string {
	var builder strings.Builder
	builder.WriteString("# generated by retailgate netpolicy --format nftables\n")
	builder.WriteString("# table " + NFTTable + ": new management connections to protected controllers\n")
	builder.WriteString("# are accepted only from the listed gate sources; everything else is logged and dropped.\n")
	builder.WriteString("# Honest limit: only traffic that traverses this host is enforced (routing/NAT/bridge required).\n")
	builder.WriteString("# protected endpoints: " + endpointList(plan) + "\n")
	builder.WriteString("# gate sources: " + strings.Join(plan.sourceSummary(), ", ") + "\n\n")
	builder.WriteString("table inet " + NFTTable + " {\n")

	hasV4 := len(plan.SourcesV4) > 0
	hasV6 := len(plan.SourcesV6) > 0
	if hasV4 {
		builder.WriteString("\tset gate_sources_v4 {\n\t\ttype ipv4_addr\n\t\tflags interval\n\t\telements = { " + joinPrefixes(plan.SourcesV4) + " }\n\t}\n\n")
	}
	if hasV6 {
		builder.WriteString("\tset gate_sources_v6 {\n\t\ttype ipv6_addr\n\t\tflags interval\n\t\telements = { " + joinPrefixes(plan.SourcesV6) + " }\n\t}\n\n")
	}
	if hasV4 && len(v4Endpoints(plan)) > 0 {
		builder.WriteString("\tset protected_v4 {\n\t\ttype ipv4_addr . inet_service\n\t\tflags interval\n\t\telements = { " + joinElements(v4Endpoints(plan)) + " }\n\t}\n\n")
	}
	if hasV6 && len(v6Endpoints(plan)) > 0 {
		builder.WriteString("\tset protected_v6 {\n\t\ttype ipv6_addr . inet_service\n\t\tflags interval\n\t\telements = { " + joinElements(v6Endpoints(plan)) + " }\n\t}\n\n")
	}

	builder.WriteString("\tchain forward {\n")
	builder.WriteString("\t\ttype filter hook forward priority -5; policy accept;\n")
	builder.WriteString("\t\tct state established,related accept comment \"retailgate: return traffic of allowed sessions\"\n")
	if hasV4 && len(v4Endpoints(plan)) > 0 {
		builder.WriteString("\t\tip saddr @gate_sources_v4 ip daddr . tcp dport @protected_v4 accept comment \"retailgate: gate source -> protected controller\"\n")
	}
	if hasV6 && len(v6Endpoints(plan)) > 0 {
		builder.WriteString("\t\tip6 saddr @gate_sources_v6 ip6 daddr . tcp dport @protected_v6 accept comment \"retailgate: gate source -> protected controller\"\n")
	}
	if hasV4 && len(v4Endpoints(plan)) > 0 {
		builder.WriteString("\t\tip daddr . tcp dport @protected_v4 log prefix \"" + LogPrefix + "\" flags all counter drop comment \"retailgate: direct access to protected controller denied\"\n")
	}
	if hasV6 && len(v6Endpoints(plan)) > 0 {
		builder.WriteString("\t\tip6 daddr . tcp dport @protected_v6 log prefix \"" + LogPrefix + "\" flags all counter drop comment \"retailgate: direct access to protected controller denied\"\n")
	}
	builder.WriteString("\t}\n")
	builder.WriteString("}\n")
	return builder.String()
}

// rollbackNFTables removes the whole dedicated table.
func rollbackNFTables() string {
	return "# generated by retailgate netpolicy --format nftables (rollback)\n" +
		"nft delete table inet " + NFTTable + " 2>/dev/null || true\n"
}

// v4Endpoints returns the IPv4 endpoints.
func v4Endpoints(plan Plan) []Endpoint {
	out := make([]Endpoint, 0, len(plan.Endpoints))
	for _, endpoint := range plan.Endpoints {
		if endpoint.IP.Is4() {
			out = append(out, endpoint)
		}
	}
	return out
}

// v6Endpoints returns the IPv6 endpoints.
func v6Endpoints(plan Plan) []Endpoint {
	out := make([]Endpoint, 0, len(plan.Endpoints))
	for _, endpoint := range plan.Endpoints {
		if endpoint.IP.Is6() {
			out = append(out, endpoint)
		}
	}
	return out
}

// joinPrefixes renders a comma separated set element list.
func joinPrefixes(prefixes []netip.Prefix) string {
	parts := make([]string, 0, len(prefixes))
	for _, prefix := range prefixes {
		parts = append(parts, prefix.String())
	}
	return strings.Join(parts, ", ")
}

// joinElements renders IPv4/IPv6 address . service elements.
func joinElements(endpoints []Endpoint) string {
	parts := make([]string, 0, len(endpoints))
	for _, endpoint := range endpoints {
		parts = append(parts, endpoint.IP.String()+" . "+strconv.Itoa(int(endpoint.Port)))
	}
	return strings.Join(parts, ", ")
}

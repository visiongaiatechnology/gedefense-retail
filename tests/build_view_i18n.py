#!/usr/bin/env python3
"""Build the view i18n catalog and refactor the eight dashboard views.

Inputs (repo):  src/retail/internal/webui/web/js/views/<view>.js
Temporary parts (generated by the test tooling): view_i18n_manifest.json, view_i18n_part{1..5}.json
Outputs:        docs/retail/i18n-view-keys.json
                refactored view files (visible strings -> t('view.<view>.<slug>', …))

The script is deterministic and idempotent for the translation data. It fails
loudly instead of silently dropping a message: missing translations, placeholder
mismatches or literals that are not found are reported and cause a non-zero exit.
"""

from __future__ import annotations

import io
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(REPO, "src", "retail", "internal", "webui", "web")
VIEWS = os.path.join(WEB, "js", "views")
DOCS = os.path.join(REPO, "docs", "retail")
TMP = os.environ.get("TEMP", os.environ.get("TMP", "/tmp"))

LANGUAGES = ["de", "en", "fr", "it", "es", "ja", "zh", "ru"]
VIEW_NAMES = ["overview", "site", "assets", "coldchain", "access", "threat", "integrity", "incident", "incident-dialogs"]
IMPORT_LINE = "import { t } from '../i18n/index.js';"

LITERAL = re.compile(r"""(?P<q>['"`])(?P<v>(?:\\.|(?!(?P=q)).)*?)(?P=q)""")
PLACEHOLDER = re.compile(r"%[sdvq]|\{[A-Za-z0-9_]+\}")

# Literals that must not be wrapped in t():
#   107 = `sensor-${index}` is a DOM id, not visible text.
SKIP_IDS = {107}
# Nested-template entries are rewritten by hand after the automated pass because
# the interpolated expression itself contains user-visible German literals.
MANUAL_KEYS = {
    44: "view.overview.audit_chain",
    60: "view.site.zone_asset_count",
    69: "view.site.asset_list_summary",
    108: "view.coldchain.chart_sensor_toggle",
    225: "view.incident.case_count",
}


def load_json(path):
    with io.open(path, encoding="utf-8") as handle:
        return json.load(handle)


def split_template(content):
    """Split a template literal body into static parts and ${…} expressions."""
    parts = []
    expressions = []
    index = 0
    while True:
        start = content.find("${", index)
        if start < 0:
            parts.append(content[index:])
            break
        parts.append(content[index:start])
        depth = 0
        cursor = start + 1
        while cursor < len(content):
            char = content[cursor]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    break
            cursor += 1
        expressions.append(content[start + 2:cursor])
        index = cursor + 1
    return parts, expressions


def canonical(content):
    parts, expressions = split_template(content)
    result = parts[0]
    for number, _ in enumerate(expressions, start=1):
        result += "{p%d}" % number + parts[number]
    return result


def placeholders(value):
    found = []
    for token in PLACEHOLDER.findall(value):
        name = token[0]
        if name == "%":
            found.append(token)
        else:
            found.append(token)
    return sorted(found)


def slugify(text):
    slug = text.lower()
    slug = slug.replace("ä", "ae").replace("ö", "oe").replace("ü", "ue").replace("ß", "ss")
    slug = re.sub(r"[^a-z0-9]+", "_", slug).strip("_")
    if not slug:
        slug = "message"
    if slug[0].isdigit():
        slug = "m_" + slug
    return slug[:48].rstrip("_")


def main():
    manifest = load_json(os.path.join(TMP, "view_i18n_manifest.json"))
    translations = {}
    for number in range(1, 6):
        part = load_json(os.path.join(TMP, "view_i18n_part%d.json" % number))
        for key, values in part.items():
            if key in translations:
                print("duplicate translation id", key, file=sys.stderr)
                return 1
            translations[int(key)] = values
    extra = load_json(os.path.join(TMP, "view_i18n_extra.json"))

    errors = []
    mapping = {}  # canonical -> entry
    reuse_entries = []
    used_keys = set()
    per_file_keys = {}
    catalog = {}

    def add_catalog(key, lang_values, note_source):
        if key in catalog:
            errors.append("duplicate catalog key %r (%s)" % (key, note_source))
            return
        catalog[key] = lang_values

    for entry in manifest:
        entry_id = entry["id"]
        if entry_id in SKIP_IDS:
            continue
        if entry_id in MANUAL_KEYS:
            key = MANUAL_KEYS[entry_id]
            if entry_id not in translations:
                errors.append("manual id %d has no translations" % entry_id)
                continue
            _validate_translations(entry, translations[entry_id], errors)
            values = dict(zip(LANGUAGES, [entry["canonical"]] + translations[entry_id]))
            add_catalog(key, values, "manual id %d" % entry_id)
            used_keys.add(key)
            continue
        if entry["reuse"]:
            reuse_entries.append({"literal": entry["src"], "key": entry["reuse"], "file": entry["file"]})
            mapping[entry["canonical"]] = {"key": entry["reuse"], "params": entry["params"], "id": entry_id}
            continue
        if entry_id not in translations:
            errors.append("missing translations for id %d (%s:%d)" % (entry_id, entry["file"], entry["line"]))
            continue
        values = _validate_translations(entry, translations[entry_id], errors)
        if not values or not values[0]:
            continue
        english = values[0]  # values are [en, fr, it, es, ja, zh, ru]
        view = entry["file"]
        base = "view.%s.%s" % (view.replace("incident-dialogs", "incident_dialogs"), slugify(english))
        key = base
        suffix = 2
        while key in used_keys:
            key = "%s_%d" % (base, suffix)
            suffix += 1
        used_keys.add(key)
        per_file_keys.setdefault(view, []).append(key)
        lang_values = dict(zip(LANGUAGES, [entry["canonical"]] + values))
        add_catalog(key, lang_values, "id %d" % entry_id)
        mapping[entry["canonical"]] = {"key": key, "params": entry["params"], "id": entry_id}

    # Extras (plural nouns, markers, audit labels). Manual keys win on conflict.
    for key, lang_values in extra.get("extras", {}).items():
        if key in catalog:
            continue
        missing = [lang for lang in LANGUAGES if lang not in lang_values]
        if missing:
            errors.append("extra %r misses languages %s" % (key, missing))
            continue
        add_catalog(key, {lang: lang_values[lang] for lang in LANGUAGES}, "extra")
        used_keys.add(key)

    # Late additions for literals the extraction heuristic missed (lower-case
    # phrases without umlauts, e.g. "unbekannt", "noch offen"). Files may also
    # map a literal onto an existing locale key instead of adding a new message.
    for late_name in ("view_i18n_part6.json", "view_i18n_part7.json"):
        late_path = os.path.join(TMP, late_name)
        if not os.path.isfile(late_path):
            continue
        late = load_json(late_path)
        for view, entries in late.items():
            if view in ("late", "reuse"):
                continue
            for src, values in entries.items():
                if len(values) != 7:
                    errors.append("late %r/%r: expected 7 translations" % (view, src))
                    continue
                entry = {"id": -1, "file": view, "line": 0, "src": src,
                         "canonical": canonical(src), "params": len(split_template(src)[1])}
                _validate_translations(entry, values, errors)
                key = "view.%s.%s" % (view.replace("incident-dialogs", "incident_dialogs"), slugify(values[0]))
                base = key
                suffix = 2
                while key in used_keys:
                    key = "%s_%d" % (base, suffix)
                    suffix += 1
                used_keys.add(key)
                add_catalog(key, dict(zip(LANGUAGES, [entry["canonical"]] + values)), "late %r" % src)
                mapping[entry["canonical"]] = {"key": key, "params": entry["params"], "id": -1}
        for view, entries in late.get("reuse", {}).items():
            for src, existing_key in entries.items():
                mapping[canonical(src)] = {"key": existing_key, "params": len(split_template(src)[1]), "id": -1}
                reuse_entries.append({"literal": src, "key": existing_key, "file": view})

    if errors:
        for message in errors:
            print("ERROR " + message, file=sys.stderr)
        return 1

    # Refactor the view files.
    replaced_total = 0
    for view in VIEW_NAMES:
        path = os.path.join(VIEWS, view + ".js")
        with io.open(path, encoding="utf-8") as handle:
            text = handle.read()
        if "from '../i18n/index.js'" not in text:
            imports = list(re.finditer(r"(?m)^import[\s\S]*?;\s*$", text))
            if not imports:
                errors.append("%s: no import block found" % view)
                continue
            insert_at = imports[-1].end()
            text = text[:insert_at] + "\n" + IMPORT_LINE + text[insert_at:]
        lines = text.split("\n")
        replaced = 0
        for number, line in enumerate(lines):
            if not LITERAL.search(line):
                continue

            def replace(match):
                nonlocal replaced
                content = match.group("v")
                key_info = mapping.get(canonical(content))
                if key_info is None:
                    return match.group(0)
                parts, expressions = split_template(content)
                if key_info["params"] > 0:
                    params = ", ".join("p%d: %s" % (i + 1, expr) for i, expr in enumerate(expressions))
                    expression = "t('%s', { %s })" % (key_info["key"], params)
                else:
                    expression = "t('%s')" % key_info["key"]
                replaced += 1
                return expression

            lines[number] = LITERAL.sub(replace, line)
        replaced_total += replaced
        with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(lines))

    # Final catalog document.
    document = {
        "version": 1,
        "product": "GeDefense Retail",
        "generated_by": "GeDefense Retail test tooling",
        "languages": LANGUAGES,
        "view_files": ["js/views/%s.js" % view for view in VIEW_NAMES],
        "keys": {key: catalog[key] for key in sorted(catalog)},
        "reused_keys": reuse_entries,
        "skipped_literals": [
            {"id": 107, "literal": "sensor-${index}", "reason": "DOM id, not visible text"},
        ],
        "notes": (
            "Visible strings of the eight main dashboard views. Merge keys into "
            "js/i18n/locales/<lang>.js. rule_templates map rule_id to localized "
            "alert title/summary; views use t('rule.<rule_id>.title', params, serverText)."
        ),
        "rule_templates": extra.get("rule_templates", {}),
    }
    os.makedirs(DOCS, exist_ok=True)
    with io.open(os.path.join(DOCS, "i18n-view-keys.json"), "w", encoding="utf-8", newline="\n") as handle:
        json.dump(document, handle, ensure_ascii=False, indent=1)
        handle.write("\n")

    print(json.dumps({
        "keys": len(catalog),
        "reused_keys": len(reuse_entries),
        "rule_templates": len(document["rule_templates"]),
        "replaced_literals": replaced_total,
        "view_keys": {view: len(keys) for view, keys in sorted(per_file_keys.items())},
    }, indent=1))
    return 0


def _validate_translations(entry, values, errors):
    if len(values) != 7:
        errors.append("id %d: expected 7 translations, got %d" % (entry["id"], len(values)))
        return ["", "", "", "", "", "", ""]
    wanted = placeholders(entry["canonical"])
    for index, language in enumerate(LANGUAGES[1:]):
        got = placeholders(values[index])
        if wanted != got:
            errors.append("id %d %s: placeholders %s != %s (%r)" % (
                entry["id"], language, got, wanted, values[index]))
    return values


if __name__ == "__main__":
    sys.exit(main())
